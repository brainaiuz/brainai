package com.edatasite.workforce.gwt.core.server.office365.resources;

import com.edatasite.workforce.gwt.core.server.office365.resources.base.Office365BaseResource;

/**
 * Created by umakarimov on 9/30/15.
 */
public class Office365Identity extends Office365BaseResource {

    private String id;
    private String displayName;

    /**
     * @see http://graph.microsoft.io/GraphDocuments/api-reference/v1.0/resources/identity.htm
     */
    public Office365Identity() {
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getDisplayName() {
        return displayName;
    }

    public void setDisplayName(String displayName) {
        this.displayName = displayName;
    }
}
