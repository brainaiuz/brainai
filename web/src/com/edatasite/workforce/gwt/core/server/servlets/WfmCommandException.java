package com.edatasite.workforce.gwt.core.server.servlets;

public class WfmCommandException extends Exception {

    private static final long serialVersionUID = 7896662328909503836L;

    public WfmCommandException() {

    }

    public WfmCommandException(String message) {
        super(message);

    }

    public WfmCommandException(Throwable cause) {
        super(cause);

    }

    public WfmCommandException(String message, Throwable cause) {
        super(message, cause);

    }

}
